// --- безопасный калькулятор (рекурсивный спуск, без eval) ---
function calc(expr){
  expr = expr.replace(/,/g,'.').replace(/×/g,'*').replace(/÷/g,'/').replace(/−/g,'-').replace(/\s+/g,'');
  let i = 0;
  const peek = () => expr[i], next = () => expr[i++];
  function parseExpr(){ let v = parseTerm(); while(peek()==='+'||peek()==='-'){ const op = next(); const r = parseTerm(); v = op==='+' ? v+r : v-r; } return v; }
  function parseTerm(){ let v = parsePow(); while(peek()==='*'||peek()==='/'||peek()==='%'){ const op = next(); const r = parsePow(); v = op==='*' ? v*r : op==='/' ? v/r : v%r; } return v; }
  function parsePow(){ let v = parseUnary(); if(peek()==='^'){ next(); v = Math.pow(v, parsePow()); } return v; }
  function parseUnary(){ if(peek()==='-'){ next(); return -parseUnary(); } if(peek()==='+'){ next(); return parseUnary(); } return parseAtom(); }
  function parseAtom(){
    if(peek()==='('){ next(); const v = parseExpr(); if(peek()!==')') throw 0; next(); return v; }
    const m = /^\d+(?:\.\d+)?/.exec(expr.slice(i));
    if(!m) throw 0;
    i += m[0].length; return parseFloat(m[0]);
  }
  const v = parseExpr();
  if(i < expr.length || !isFinite(v)) throw 0;
  return Math.round(v*1e10)/1e10;
}

// --- простое резюме текста: самые «важные» предложения по частоте слов ---
function summarize(text){
  const clean = (text||'').replace(/\s+/g,' ').trim();
  if(!clean) return 'На странице нет текста для резюме.';
  if(clean.length < 220) return clean;
  const sents = clean.match(/[^.!?…]{25,}[.!?…]/g) || [clean.slice(0, 400)];
  const freq = {};
  for(const w of clean.toLowerCase().match(/[a-zа-яё]{4,}/g) || []) freq[w] = (freq[w]||0)+1;
  const scored = sents.map(s => {
    const ws = s.toLowerCase().match(/[a-zа-яё]{4,}/g) || [];
    return { s, sc: ws.reduce((a,w) => a + (freq[w]||0), 0) };
  }).sort((a,b) => b.sc - a.sc).slice(0, 4);
  scored.sort((a,b) => sents.indexOf(a.s) - sents.indexOf(b.s));
  return scored.map(x => x.s.trim()).join(' ');
}

async function external(text, settings){
  const r = await fetch(settings.aiEndpoint, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', 'Authorization': 'Bearer ' + settings.aiKey },
    body: JSON.stringify({
      model: settings.aiModel || 'gpt-4o-mini',
      messages: [
        { role: 'system', content: 'Ты — НОЧЬ, лаконичный помощник чёрного браузера BLACK. Отвечай по-русски, коротко и по делу.' },
        { role: 'user', content: text },
      ],
    }),
  });
  if(!r.ok) throw new Error('api ' + r.status);
  const j = await r.json();
  const out = j.choices && j.choices[0] && j.choices[0].message && j.choices[0].message.content;
  if(!out) throw new Error('empty');
  return out.trim();
}

